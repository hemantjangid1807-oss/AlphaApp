# Headless phone-size UI test. Usage: python3 tests/ui_test.py [outdir]
import sys, subprocess, time, os
from playwright.sync_api import sync_playwright
out = sys.argv[1] if len(sys.argv) > 1 else '/tmp/shots'
os.makedirs(out, exist_ok=True)
www = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'app', 'src', 'main', 'assets', 'www')
srv = subprocess.Popen([sys.executable, '-m', 'http.server', '8765', '--directory', www], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(0.8)
errors = []
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        ctx = b.new_context(viewport={'width': 393, 'height': 852}, device_scale_factor=2, is_mobile=True, has_touch=True)
        pg = ctx.new_page()
        pg.on('console', lambda m: errors.append('console.' + m.type + ': ' + m.text) if m.type in ('error', 'warning') else None)
        pg.on('pageerror', lambda e: errors.append('pageerror: ' + str(e)))
        pg.goto('http://localhost:8765/index.html')
        pg.wait_for_function("document.querySelector('#overlay').classList.contains('hidden')", timeout=30000)
        pg.wait_for_timeout(400)
        pg.screenshot(path=f'{out}/1_simulate.png')
        # typo -> error message
        pg.fill('#expr', 'rank(-ts_delta(clsoe, 5))')
        pg.wait_for_timeout(400)
        print('status (typo):', pg.inner_text('#status'))
        pg.screenshot(path=f'{out}/1b_error.png', clip={'x': 0, 'y': 0, 'width': 393, 'height': 330})
        # example blend with test period
        pg.click('#btnExamples'); pg.wait_for_timeout(400)
        pg.screenshot(path=f'{out}/2_examples.png')
        pg.click('.ex-item[data-i="10"]'); pg.wait_for_timeout(400)
        pg.click('.stepper[data-key="testPeriod"] button[data-d="1"]')
        pg.click('.stepper[data-key="testPeriod"] button[data-d="1"]')
        pg.click('#btnSimulate')
        pg.wait_for_selector('#view-results.active .grade', timeout=30000)
        pg.wait_for_timeout(500)
        pg.screenshot(path=f'{out}/3_results_top.png')
        pg.evaluate("document.querySelector('#main').scrollTop = 600")
        pg.wait_for_timeout(200)
        pg.screenshot(path=f'{out}/3_results_mid.png')
        pg.evaluate("document.querySelector('#main').scrollTop = 1300")
        pg.wait_for_timeout(200)
        pg.screenshot(path=f'{out}/3_results_low.png')
        pg.evaluate("document.querySelector('#main').scrollTop = 0")
        # scrub the chart
        box = pg.query_selector('#chart').bounding_box()
        pg.mouse.move(box['x'] + box['width'] * 0.6, box['y'] + 100); pg.mouse.down(); pg.mouse.move(box['x'] + box['width'] * 0.62, box['y'] + 100)
        pg.wait_for_timeout(200)
        pg.screenshot(path=f'{out}/3b_scrub.png', clip={'x': 0, 'y': box['y'] - 10, 'width': 393, 'height': box['height'] + 60})
        pg.mouse.up()
        pg.click('#chartTabs button[data-c="cov"]'); pg.wait_for_timeout(200)
        pg.screenshot(path=f'{out}/3c_positions.png', clip={'x': 0, 'y': box['y'] - 10, 'width': 393, 'height': box['height'] + 60})
        print('summary:', pg.inner_text('.grade').replace('\n', ' | '))
        pg.click('#btnStar'); pg.wait_for_timeout(300)
        # a second run to populate history
        pg.click('#tabbar button[data-tab="simulate"]')
        pg.fill('#expr', 'rank(-ts_sum(returns, 5))')
        pg.click('#btnSimulate')
        pg.wait_for_selector('#view-results.active .grade', timeout=30000)
        pg.wait_for_timeout(300)
        print('checks:', pg.inner_text('.checks').replace('\n', ' | ')[:600])
        pg.click('#tabbar button[data-tab="alphas"]'); pg.wait_for_timeout(400)
        pg.screenshot(path=f'{out}/4_alphas.png')
        pg.click('#tabbar button[data-tab="data"]'); pg.wait_for_timeout(300)
        pg.screenshot(path=f'{out}/5_data.png')
        pg.click('#tabbar button[data-tab="learn"]'); pg.wait_for_timeout(300)
        pg.screenshot(path=f'{out}/6_learn.png')
        pg.fill('#opSearch', 'corr'); pg.wait_for_timeout(200)
        pg.screenshot(path=f'{out}/6b_search.png')
        pg.click('#learnTabs button[data-t="how"]'); pg.wait_for_timeout(200)
        pg.screenshot(path=f'{out}/6c_how.png')
        # reload: persistence
        pg.reload(); pg.wait_for_function("document.querySelector('#overlay').classList.contains('hidden')", timeout=30000)
        pg.click('#tabbar button[data-tab="alphas"]'); pg.wait_for_timeout(300)
        print('history after reload:', pg.eval_on_selector_all('.alpha-item', 'e => e.length'))
        b.close()
finally:
    srv.terminate()
print('errors:', errors if errors else 'none')
